/* global describe test expect*/
const user = require('../framework/services/usersController.js')
const booksSchema = require('../framework/schema/bookSchema.js')
const Ajv = require("ajv")

const ajv = new Ajv();

const booksValidate = ajv.compile(booksSchema.bookSchema)

describe('Тесты для https://bookstore.demoqa.com', () => {
    test('Успешное создание книги', async () => {
        const newUser = new user('testUser')
        await newUser.create()
        await newUser.getToken()
        await newUser.addBooks('9781593277574')
        const data = await newUser.getInfo()
        const isValid = booksValidate(data.books)
        expect(isValid).toBe(true)
        const book = data.books.find(el => el.isbn === '9781593277574')
        expect(book.isbn).toBe('9781593277574')
        expect(book.title).toBe('Understanding ECMAScript 6')
        expect(book.subTitle).toBe('The Definitive Guide for JavaScript Developers')
        expect(book.publisher).toBe('No Starch Press')
        expect(book.pages).toBe(352)
    }, 10000)
    test('Неуспешное создание книги', async () => {
        const newUser = new user('testUser')
        await newUser.create()
        await newUser.getToken()
        await newUser.addBooks('9781593277572')
        const data = await newUser.getInfo()
        expect(data.books).toHaveLength(0)
    }, 10000)
    test('Успешное обновление книги', async () => {
        const newUser = new user('testUser')
        await newUser.create()
        await newUser.getToken()
        await newUser.addBooks('9781593277574')
        let data = await newUser.getInfo()
        expect(data.books).toHaveLength(1)
        expect(data.books.find(el => el.isbn === '9781593277574').title).toBe('Understanding ECMAScript 6')
        await newUser.changeBook('9781593277574', '9781491950296')
        data = await newUser.getInfo()
        expect(data.books).toHaveLength(1)
        expect(data.books.find(el => el.isbn === '9781491950296').title).toBe('Programming JavaScript Applications')
    }, 10000)
    test('Неуспешное обновление книги', async () => {
        const newUser = new user('testUser')
        await newUser.create()
        await newUser.getToken()
        await newUser.addBooks('9781593277574')
        let data = await newUser.getInfo()
        expect(data.books).toHaveLength(1)
        expect(data.books.find(el => el.isbn === '9781593277574').title).toBe('Understanding ECMAScript 6')
        await newUser.changeBook('9781593277574', '9781491950299')
        data = await newUser.getInfo()
        expect(data.books).toHaveLength(1)
        expect(data.books.find(el => el.isbn === '9781593277574').title).toBe('Understanding ECMAScript 6')
        expect(data.books.find(el => el.isbn === '9781491950299')).toBeUndefined()
    }, 10000)
    test('Успешное удаление книги', async () => {
        const newUser = new user('testUser')
        await newUser.create()
        await newUser.getToken()
        await newUser.addBooks('9781593277574')
        let data = await newUser.getInfo()
        expect(data.books).toHaveLength(1)
        expect(data.books.find(el => el.isbn === '9781593277574').title).toBe('Understanding ECMAScript 6')
        await newUser.deleteBook('9781593277574')
        data = await newUser.getInfo()
        expect(data.books).toHaveLength(0)
        expect(data.books.find(el => el.isbn === '9781593277574')).toBeUndefined()
    }, 10000)
})
